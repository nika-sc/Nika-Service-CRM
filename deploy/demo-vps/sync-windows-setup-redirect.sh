#!/bin/bash
# Point old Windows SETUP download URLs at the single EXE in the mirror dir.
# Run on DEMO after each release: copy the new file, delete the previous one, then this script.
set -euo pipefail

DIR=/var/www/nikacrm-downloads
SNIPPET=/etc/nginx/snippets/nikacrm-setup-latest.conf
PATTERN='^NikaCRM-Offline-Setup-[0-9]+\.[0-9]+\.[0-9]+-x64\.exe$'

mapfile -t files < <(find "$DIR" -maxdepth 1 -type f -printf '%f\n' | grep -E "$PATTERN" | sort)
if [[ ${#files[@]} -ne 1 ]]; then
  echo "expected exactly one NikaCRM-Offline-Setup-X.Y.Z-x64.exe in $DIR, found ${#files[@]}" >&2
  printf '  %s\n' "${files[@]:-}" >&2
  exit 1
fi

name="${files[0]}"
if [[ ! "$name" =~ $PATTERN ]]; then
  echo "refusing unexpected filename: $name" >&2
  exit 1
fi

tmp=$(mktemp)
backup=""
if [[ -f "$SNIPPET" ]]; then
  backup=$(mktemp)
  cp -a "$SNIPPET" "$backup"
fi

cat > "$tmp" << EOF
# Generated by nikacrm-sync-setup-redirect.sh from the file in ${DIR}.
# Do not edit the version by hand.
location @nikacrm_setup_latest {
    add_header Cache-Control "no-store" always;
    return 302 /downloads/${name};
}
EOF
install -m 644 "$tmp" "$SNIPPET"
rm -f "$tmp"

if ! nginx -t; then
  echo "nginx -t failed, restoring previous snippet" >&2
  if [[ -n "$backup" ]]; then
    cp -a "$backup" "$SNIPPET"
  else
    rm -f "$SNIPPET"
  fi
  rm -f "$backup"
  exit 1
fi
rm -f "$backup"
systemctl reload nginx
echo "old SETUP urls -> /downloads/${name}"
